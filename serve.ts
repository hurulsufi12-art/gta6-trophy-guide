// A tiny static server for the guide (Node 22, standard library only), so it
// can be tried locally without a build step: `node serve.ts` serves app/ on
// http://localhost:8080 (`--port <n>` for another port) and the screenshots
// under /shots/. It sends the MIME types a browser needs, refuses any path
// outside those two roots, and otherwise does nothing clever: this is a
// development convenience, not a web server for the internet.
import { createReadStream, statSync } from 'node:fs';
import { createServer } from 'node:http';
import { extname, join, normalize, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const appRoot = resolve(join(here, 'app'));
const shotsRoot = resolve(join(here, 'screenshots'));
const args = process.argv.slice(2);
const portArg = args.indexOf('--port');
const wanted = portArg === -1 ? 8080 : Number(args[portArg + 1]);
const port = Number.isInteger(wanted) && wanted > 0 && wanted < 65536 ? wanted : 8080;

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.webmanifest': 'application/manifest+json',
};

function pickRoot(pathname) {
  if (pathname === '/shots' || pathname.startsWith('/shots/')) {
    return { root: shotsRoot, rel: pathname.slice('/shots'.length) || '/' };
  }
  return { root: appRoot, rel: pathname };
}

createServer((request, response) => {
  const url = new URL(request.url ?? '/', 'http://localhost');
  let pathname;
  try {
    pathname = decodeURIComponent(url.pathname);
  } catch {
    response.writeHead(400).end('bad request');
    return;
  }
  if (pathname.endsWith('/')) pathname += 'index.html';
  const { root, rel } = pickRoot(pathname);
  const file = resolve(join(root, normalize(rel)));
  if (file !== root && !file.startsWith(root + sep)) {
    response.writeHead(403).end('forbidden');
    return;
  }
  let size;
  try {
    const stats = statSync(file);
    if (!stats.isFile()) throw new Error('not a file');
    size = stats.size;
  } catch {
    response.writeHead(404).end('not found');
    return;
  }
  response.writeHead(200, {
    'content-type': TYPES[extname(file).toLowerCase()] ?? 'application/octet-stream',
    'content-length': size,
    'cache-control': 'no-store',
  });
  createReadStream(file).pipe(response);
  console.log(`${request.method} ${url.pathname} -> 200`);
}).listen(port, '127.0.0.1', () => {
  console.log(`Vice Route is on http://localhost:${port}`);
});
